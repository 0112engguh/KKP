CREATE DATABASE IF NOT EXISTS kkp_sd CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE kkp_sd;
SET NAMES utf8mb4;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS poin, badge, verifikasi_kebiasaan, detail_jurnal_kebiasaan, jurnal_kebiasaan, kebiasaan, guru_kelas,
    jawaban_siswa, hasil_ujian, kelompok_ujian_soal, kelompok_ujian, ujian_soal, ujian, opsi_jawaban, bank_soal,
    absensi_detail, absensi, siswa, orang_tua, kelas, mata_pelajaran, guru, users, roles;
SET FOREIGN_KEY_CHECKS = 1;

-- ------------------------------------------------------------
-- 1. Akun & role
-- ------------------------------------------------------------
CREATE TABLE roles (
    id        TINYINT UNSIGNED PRIMARY KEY,
    nama_role VARCHAR(20) NOT NULL UNIQUE
) ENGINE=InnoDB;

-- username = NIP (admin/guru), NISN (siswa), NISN anak pertama (orang tua)
CREATE TABLE users (
    id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    role_id    TINYINT UNSIGNED NOT NULL,
    username   VARCHAR(30) NOT NULL,
    password   VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_users_role_username (role_id, username),
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
) ENGINE=InnoDB;

CREATE TABLE guru (
    id      INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id INT UNSIGNED NOT NULL UNIQUE,
    nip     VARCHAR(30) NOT NULL UNIQUE,
    nama    VARCHAR(100) NOT NULL,
    email   VARCHAR(100) NULL,
    CONSTRAINT fk_guru_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE guru_kelas (
    guru_id  INT UNSIGNED NOT NULL,
    kelas_id INT UNSIGNED NOT NULL,
    PRIMARY KEY (guru_id, kelas_id),
    CONSTRAINT fk_gk_guru  FOREIGN KEY (guru_id)  REFERENCES guru(id) ON DELETE CASCADE,
    CONSTRAINT fk_gk_kelas FOREIGN KEY (kelas_id) REFERENCES kelas(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE orang_tua (
    id      INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id INT UNSIGNED NOT NULL UNIQUE,
    nama    VARCHAR(100) NOT NULL,
    no_hp   VARCHAR(20) NULL,
    CONSTRAINT fk_ortu_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- 2. Data master
-- ------------------------------------------------------------
CREATE TABLE kelas (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nama_kelas    VARCHAR(20) NOT NULL UNIQUE,
    tingkat       TINYINT UNSIGNED NOT NULL,
    wali_kelas_id INT UNSIGNED NULL,
    CONSTRAINT fk_kelas_wali FOREIGN KEY (wali_kelas_id) REFERENCES guru(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE siswa (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id       INT UNSIGNED NOT NULL UNIQUE,
    nisn          VARCHAR(20) NOT NULL UNIQUE,
    nama          VARCHAR(100) NOT NULL,
    jenis_kelamin ENUM('L','P') NOT NULL,
    tanggal_lahir DATE NULL,
    alamat        VARCHAR(255) NULL,
    kelas_id      INT UNSIGNED NOT NULL,
    orang_tua_id  INT UNSIGNED NULL,
    status        ENUM('aktif','nonaktif') NOT NULL DEFAULT 'aktif',
    CONSTRAINT fk_siswa_user  FOREIGN KEY (user_id)      REFERENCES users(id)     ON DELETE CASCADE,
    CONSTRAINT fk_siswa_kelas FOREIGN KEY (kelas_id)     REFERENCES kelas(id),
    CONSTRAINT fk_siswa_ortu  FOREIGN KEY (orang_tua_id) REFERENCES orang_tua(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE mata_pelajaran (
    id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nama_mapel VARCHAR(80) NOT NULL UNIQUE,
    keterangan VARCHAR(255) NULL
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- 3. Absensi
-- ------------------------------------------------------------
CREATE TABLE absensi (
    id       INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    kelas_id INT UNSIGNED NOT NULL,
    tanggal  DATE NOT NULL,
    guru_id  INT UNSIGNED NULL,
    UNIQUE KEY uq_absensi_kelas_tanggal (kelas_id, tanggal),
    CONSTRAINT fk_absensi_kelas FOREIGN KEY (kelas_id) REFERENCES kelas(id) ON DELETE CASCADE,
    CONSTRAINT fk_absensi_guru  FOREIGN KEY (guru_id)  REFERENCES guru(id)  ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE absensi_detail (
    id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    absensi_id INT UNSIGNED NOT NULL,
    siswa_id   INT UNSIGNED NOT NULL,
    status     ENUM('H','I','S','A') NOT NULL,
    UNIQUE KEY uq_detail_absensi_siswa (absensi_id, siswa_id),
    CONSTRAINT fk_adetail_absensi FOREIGN KEY (absensi_id) REFERENCES absensi(id) ON DELETE CASCADE,
    CONSTRAINT fk_adetail_siswa   FOREIGN KEY (siswa_id)   REFERENCES siswa(id)   ON DELETE CASCADE
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- 4. TKA online
-- ------------------------------------------------------------
CREATE TABLE bank_soal (
    id             INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    mapel_id       INT UNSIGNED NOT NULL,
    kategori       VARCHAR(60) NULL,
    tingkat        ENUM('mudah','sedang','sulit') NOT NULL DEFAULT 'sedang',
    pertanyaan     TEXT NOT NULL,
    gambar         VARCHAR(255) NULL,
    kunci_jawaban  CHAR(1) NOT NULL,
    pembahasan     TEXT NULL,
    CONSTRAINT fk_soal_mapel FOREIGN KEY (mapel_id) REFERENCES mata_pelajaran(id)
) ENGINE=InnoDB;

CREATE TABLE opsi_jawaban (
    id      INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    soal_id INT UNSIGNED NOT NULL,
    label   CHAR(1) NOT NULL,
    teks    VARCHAR(500) NOT NULL,
    UNIQUE KEY uq_opsi_soal_label (soal_id, label),
    CONSTRAINT fk_opsi_soal FOREIGN KEY (soal_id) REFERENCES bank_soal(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- jumlah soal tidak disimpan (dihitung dari ujian_soal) agar tidak redundan
CREATE TABLE ujian (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nama_ujian    VARCHAR(150) NOT NULL,
    mapel_id      INT UNSIGNED NOT NULL,
    kelas_id      INT UNSIGNED NOT NULL,
    durasi_menit  SMALLINT UNSIGNED NOT NULL,
    waktu_mulai   DATETIME NOT NULL,
    waktu_selesai DATETIME NOT NULL,
    status        ENUM('draft','aktif') NOT NULL DEFAULT 'draft',
    CONSTRAINT fk_ujian_mapel FOREIGN KEY (mapel_id) REFERENCES mata_pelajaran(id),
    CONSTRAINT fk_ujian_kelas FOREIGN KEY (kelas_id) REFERENCES kelas(id)
) ENGINE=InnoDB;

CREATE TABLE ujian_soal (
    id        INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    ujian_id  INT UNSIGNED NOT NULL,
    soal_id   INT UNSIGNED NOT NULL,
    urutan    SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    UNIQUE KEY uq_ujian_soal (ujian_id, soal_id),
    CONSTRAINT fk_us_ujian FOREIGN KEY (ujian_id) REFERENCES ujian(id)     ON DELETE CASCADE,
    CONSTRAINT fk_us_soal  FOREIGN KEY (soal_id)  REFERENCES bank_soal(id)
) ENGINE=InnoDB;

-- Bank Soal parent-child: Parent = kelompok ujian, Child = soal di dalam kelompok.
-- Soal dapat dipakai ulang di beberapa kelompok tanpa duplikat (many-to-many).
CREATE TABLE kelompok_ujian (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nama_ujian    VARCHAR(150) NOT NULL,
    tahun_ajaran  VARCHAR(9) NOT NULL,          -- contoh: 2026/2027
    semester      ENUM('ganjil','genap') NOT NULL,
    kelas_id      INT UNSIGNED NOT NULL,
    status        ENUM('draft','aktif') NOT NULL DEFAULT 'draft',
    dibuat_pada   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_kelompok_tahun (tahun_ajaran),
    CONSTRAINT fk_kelompok_kelas FOREIGN KEY (kelas_id) REFERENCES kelas(id)
) ENGINE=InnoDB;

CREATE TABLE kelompok_ujian_soal (
    id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    kelompok_id INT UNSIGNED NOT NULL,
    soal_id     INT UNSIGNED NOT NULL,
    urutan      SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    bobot       DECIMAL(5,2) NOT NULL DEFAULT 1.00,
    UNIQUE KEY uq_kelompok_soal (kelompok_id, soal_id),
    CONSTRAINT fk_ks_kelompok FOREIGN KEY (kelompok_id) REFERENCES kelompok_ujian(id) ON DELETE CASCADE,
    CONSTRAINT fk_ks_soal     FOREIGN KEY (soal_id)     REFERENCES bank_soal(id)
) ENGINE=InnoDB;

CREATE TABLE hasil_ujian (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    ujian_id      INT UNSIGNED NOT NULL,
    siswa_id      INT UNSIGNED NOT NULL,
    waktu_mulai   DATETIME NOT NULL,
    waktu_selesai DATETIME NULL,
    status        ENUM('berlangsung','selesai') NOT NULL DEFAULT 'berlangsung',
    jumlah_benar  SMALLINT UNSIGNED NULL,
    jumlah_salah  SMALLINT UNSIGNED NULL,
    nilai         DECIMAL(5,2) NULL,
    UNIQUE KEY uq_hasil_ujian_siswa (ujian_id, siswa_id),
    CONSTRAINT fk_hasil_ujian FOREIGN KEY (ujian_id) REFERENCES ujian(id) ON DELETE CASCADE,
    CONSTRAINT fk_hasil_siswa FOREIGN KEY (siswa_id) REFERENCES siswa(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- benar/salah tidak disimpan per baris, dihitung dengan membandingkan ke bank_soal.kunci_jawaban
CREATE TABLE jawaban_siswa (
    id       INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    hasil_id INT UNSIGNED NOT NULL,
    soal_id  INT UNSIGNED NOT NULL,
    jawaban  CHAR(1) NULL,
    ragu     TINYINT(1) NOT NULL DEFAULT 0,
    UNIQUE KEY uq_jawaban_hasil_soal (hasil_id, soal_id),
    CONSTRAINT fk_jawab_hasil FOREIGN KEY (hasil_id) REFERENCES hasil_ujian(id) ON DELETE CASCADE,
    CONSTRAINT fk_jawab_soal  FOREIGN KEY (soal_id)  REFERENCES bank_soal(id)
) ENGINE=InnoDB;

-- ------------------------------------------------------------
-- 5. Monitoring 7 kebiasaan
-- ------------------------------------------------------------
CREATE TABLE kebiasaan (
    id             INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nama_kebiasaan VARCHAR(60) NOT NULL,
    deskripsi      VARCHAR(200) NULL
) ENGINE=InnoDB;

CREATE TABLE jurnal_kebiasaan (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    siswa_id      INT UNSIGNED NOT NULL,
    tanggal       DATE NOT NULL,
    catatan_siswa VARCHAR(255) NULL,
    foto_jurnal   VARCHAR(80) NULL,
    status        ENUM('menunggu','disetujui','ditolak') NOT NULL DEFAULT 'menunggu',
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_jurnal_siswa_tanggal (siswa_id, tanggal),
    CONSTRAINT fk_jurnal_siswa FOREIGN KEY (siswa_id) REFERENCES siswa(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE detail_jurnal_kebiasaan (
    id           INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    jurnal_id    INT UNSIGNED NOT NULL,
    kebiasaan_id INT UNSIGNED NOT NULL,
    selesai      TINYINT(1) NOT NULL DEFAULT 0,
    UNIQUE KEY uq_detail_jurnal_kebiasaan (jurnal_id, kebiasaan_id),
    CONSTRAINT fk_dj_jurnal    FOREIGN KEY (jurnal_id)    REFERENCES jurnal_kebiasaan(id) ON DELETE CASCADE,
    CONSTRAINT fk_dj_kebiasaan FOREIGN KEY (kebiasaan_id) REFERENCES kebiasaan(id)
) ENGINE=InnoDB;

CREATE TABLE verifikasi_kebiasaan (
    id                INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    jurnal_id         INT UNSIGNED NOT NULL UNIQUE,
    guru_id           INT UNSIGNED NULL,
    catatan           VARCHAR(255) NULL,
    apresiasi         VARCHAR(150) NULL,
    diverifikasi_pada DATETIME NOT NULL,
    CONSTRAINT fk_verif_jurnal FOREIGN KEY (jurnal_id) REFERENCES jurnal_kebiasaan(id) ON DELETE CASCADE,
    CONSTRAINT fk_verif_guru   FOREIGN KEY (guru_id)   REFERENCES guru(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- Poin hanya dibuat saat jurnal disetujui (1 kebiasaan selesai = 1 poin)
CREATE TABLE poin (
    id        INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    siswa_id  INT UNSIGNED NOT NULL,
    jurnal_id INT UNSIGNED NOT NULL UNIQUE,
    jumlah    SMALLINT UNSIGNED NOT NULL,
    tanggal   DATE NOT NULL,
    CONSTRAINT fk_poin_siswa  FOREIGN KEY (siswa_id)  REFERENCES siswa(id) ON DELETE CASCADE,
    CONSTRAINT fk_poin_jurnal FOREIGN KEY (jurnal_id) REFERENCES jurnal_kebiasaan(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Badge diraih otomatis bila total poin siswa >= minimal_poin
CREATE TABLE badge (
    id           INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nama_badge   VARCHAR(60) NOT NULL,
    minimal_poin INT UNSIGNED NOT NULL,
    deskripsi    VARCHAR(150) NULL,
    ikon         VARCHAR(10) NOT NULL DEFAULT '⭐'
) ENGINE=InnoDB;

